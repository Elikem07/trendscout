def all_keywords() -> list[str]:
    return [kw for kws in SEED_KEYWORDS.values() for kw in kws]


def crawl_plan() -> list[str]:
    """Interleave categories so a budget cutoff still covers every
    category (round robin by priority rank within category)."""
    plan: list[str] = []
    lists = list(SEED_KEYWORDS.values())
    for rank in range(max(len(kws) for kws in lists)):
        plan.extend(kws[rank] for kws in lists if rank < len(kws))
    return plan
